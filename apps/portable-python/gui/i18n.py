def error_code(error):
    if not isinstance(error, dict):
        return ""
    inner = error.get("error")
    if isinstance(inner, dict):
        error = inner
        inner = error.get("error")
    code = error.get("code")
    if not code and isinstance(inner, str):
        code = inner
    return str(code or "").upper()


def error_text(error):
    code = error_code(error)
    payload = error
    message = ""
    if isinstance(error, dict):
        inner = error.get("error")
        if isinstance(inner, dict):
            payload = inner
        message = str(payload.get("message") or "").strip()
    if message.lower() == "core stopped":
        return t("core_stopped")
    if code in IPC_CODES:
        return IPC_CODES[code]
    if isinstance(payload, dict):
        return ("%s %s" % (code, message)).strip() or str(payload)
    return str(error)


def is_offline_error(error):
    if error_code(error) == "OFFLINE":
        return True
    text = error_text(error).lower()
    return "offline" in text or "не в сети" in text
