"""PeerSync by Nickston portable Windows shell entrypoint (Python/Tk).

Modes:
  (default)      GUI: tray + window + live Core.
  --smoke        M0 gate: single instance, DPAPI identity, core install to a
                 stable path, spawn Core, framed IPC handshake + ping, status,
                 graceful exit. Prints "M0 SMOKE PASS" and exits 0 on success.
"""

